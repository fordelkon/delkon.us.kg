import { cells, dot, example, frame, label, line } from "./examples.ts";
import { edge } from "./types.ts";

type Value = number | string;

type Row = [title: string, values: Value[], active?: number[]];

function rows(note: string, entries: Row[]) {
	return frame(
		note,
		entries.flatMap(([title, values, active], index) => [
			label(`label-${index}`, 180, 15 + index * 68, title, 310),
			...cells(`values-${index}`, values, 29 + index * 68, active, 34),
		]),
	);
}

function trace(title: string, caption: string, note: string, entries: Row[]) {
	return example(title, caption, 68 * entries.length, rows(note, entries));
}

